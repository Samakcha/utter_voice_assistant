#!/usr/bin/env python3
"""
macOS Notes Write Smoke Test.
Exercises the AppleScript / Notes.app bridge with Hindi (Devanagari),
special symbols, and a long body.

Usage:
    ./.venv/bin/python scripts/test_notes_write.py [--reveal] [--folder FOLDER]
"""

import argparse
from datetime import datetime
import os
from pathlib import Path
import subprocess
import sys
import time

# Auto-reexec inside the virtual environment if available
PROJECT_ROOT = Path(__file__).resolve().parent.parent
venv_python = PROJECT_ROOT / ".venv" / "bin" / "python"
if venv_python.is_file() and sys.executable != str(venv_python):
    try:
        os.execv(str(venv_python), [str(venv_python)] + sys.argv)
    except Exception:
        pass

if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from engine.notes_writer import AppleScriptNotesWriter, generate_note_title


def is_notes_running() -> bool:
    """Check if macOS Notes application is currently running."""
    res = subprocess.run(
        ["osascript", "-e", 'application "Notes" is running'],
        capture_output=True,
        text=True,
        check=False,
    )
    return res.stdout.strip().lower() == "true"


def is_notes_frontmost() -> bool:
    """Check if macOS Notes application is currently the frontmost application."""
    script = 'tell application "System Events" to get name of first application process whose frontmost is true'
    res = subprocess.run(
        ["osascript", "-e", script],
        capture_output=True,
        text=True,
        check=False,
    )
    return res.stdout.strip() == "Notes"


def main() -> int:
    parser = argparse.ArgumentParser(description="Test creating a note in macOS Notes.")
    parser.add_argument("--reveal", action="store_true", help="Bring Notes to the front to reveal the created note.")
    parser.add_argument("--folder", type=str, default="", help="Folder name in Notes app to save into.")
    parser.add_argument("--close-notes", action="store_true", help="Quit Notes before testing to test background launch.")
    args = parser.parse_args()

    print("\n" + "=" * 70)
    print("MACOS NOTES INTEGRATION SMOKE TEST")
    print("=" * 70)

    if args.close_notes:
        print("• Quitting Notes app first per --close-notes...")
        subprocess.run(["osascript", "-e", 'tell application "Notes" to quit'], check=False)
        time.sleep(1.0)

    initial_running = is_notes_running()
    print(f"• Notes application initial state: {'RUNNING' if initial_running else 'CLOSED (Not running)'}")

    title = generate_note_title("Voice note {date} {time}") + " [Smoke Test]"

    # Test payload with Hindi, symbols, HTML characters, and a long body
    body_paragraphs = [
        "This is an automated verification note generated by the Voice Assistant smoke test script.",
        "Hindi / Devanagari Test (हिन्दी भाषा परीक्षण):\n"
        "नमस्ते दुनिया! यह वॉइस असिस्टेंट का परीक्षण नोट है। "
        "सभी स्वर, व्यंजन और मात्राएँ पूरी तरह सुरक्षित और स्पष्ट होनी चाहिए।",
        "Special Symbols & Math Characters:\n"
        "Bullets • Emojis 🚀 📝 ✨ 💡 | Math: ∑ ∫ π ≠ ≈ ≤ ≥ ± √ | Currencies: $100 €50 £30 ₹500 ¥1000",
        "HTML Characters & Quotes (Must be escaped safely):\n"
        "Comparison: 10 < 20 and 50 > 30 | Ampersand: Research & Development | Quotes: \"Hello\" and 'World'",
        "Long Body & Stress Testing:\n" + ("Lorem ipsum dolor sit amet, consectetur adipiscing elit. " * 30),
    ]
    full_body = "\n\n".join(body_paragraphs)
    word_count = len(full_body.split())

    print(f"• Prepared Note Title: \"{title}\"")
    print(f"• Note Body Size:      {len(full_body)} characters, {word_count} words")
    print(f"• Target Folder:       {args.folder if args.folder else '[Default Notes Folder]'}")
    print(f"• Reveal Note:         {args.reveal}")
    print("\nExecuting note creation via AppleScriptNotesWriter...")

    writer = AppleScriptNotesWriter(timeout_sec=10.0)
    result = writer.create_note(
        title=title,
        body=full_body,
        folder=args.folder,
        reveal=args.reveal,
    )

    now_running = is_notes_running()
    now_frontmost = is_notes_frontmost()

    print("\n" + "=" * 70)
    print("RESULT SUMMARY")
    print("=" * 70)
    print(f"Status:               {'✅ SUCCESS' if result.success else '❌ FAILED'}")
    print(f"Execution Latency:    {result.execution_time_sec * 1000.0:.1f} ms")
    print(f"Note ID:              {result.note_id or 'None'}")
    print(f"Custom Folder Used:   {result.used_custom_folder}")
    print(f"Notes App Running:    {now_running}")
    print(f"Notes Frontmost:      {now_frontmost} (Brought to front: {args.reveal and now_frontmost})")

    if result.success:
        print(f"\nMessage: {result.message}")
        print("Note successfully created! Check your macOS Notes app.")
        print("=" * 70 + "\n")
        return 0
    else:
        print(f"\nError Details:\n{result.error}")
        print("=" * 70 + "\n")
        return 1


if __name__ == "__main__":
    sys.exit(main())
